def get_breed_info(breed_name: str) -> dict:
    """
    Look up a breed's care information.

    Tolerates "Cattle_Gir", "Gir", "gir", "Red Sindhi" and "Red_Sindhi" alike,
    plus the alternate spellings the training folders use ("Jaffrabadi").
    Returns {} when the breed is not documented, so callers can degrade
    gracefully rather than showing placeholder facts.
    """
    if not breed_name:
        return {}

    candidate = str(breed_name).strip().lower()
    for key in (
        candidate,
        candidate.replace("_", " "),
        candidate.replace(" ", "_"),
    ):
        if key in _INDEX:
            return _INDEX[key]
        alias = _SPELLING_ALIASES.get(key.replace(" ", "_"))
        if alias and alias in _INDEX:
            return _INDEX[alias]

    # Strip a species prefix and retry ("cattle_gir" -> "gir").
    for prefix in ("cattle_", "buffalo_", "cattle ", "buffalo "):
        if candidate.startswith(prefix):
            return get_breed_info(candidate[len(prefix):])

    return {}
