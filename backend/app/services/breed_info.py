def _build_index() -> dict[str, dict]:
    index: dict[str, dict] = {}

    def register(key: str, payload: dict, species: str) -> None:
        entry = {**payload, "species": species}
        normalised = key.replace("_", " ").strip().lower()
        # Bare name, prefixed name, and space/underscore variants all resolve.
        for variant in {
            key.lower(),
            normalised,
            normalised.replace(" ", "_"),
            f"{species.lower()}_{normalised.replace(' ', '_')}",
            f"{species.lower()} {normalised}",
        }:
            index.setdefault(variant, entry)

    for name, payload in _CATTLE.items():
        register(name, payload, "Cattle")
    for name, payload in _BUFFALO.items():
        register(name, payload, "Buffalo")
    return index


_INDEX = _build_index()

# Kept for the chat service, which feeds the breed table to the model as context.
